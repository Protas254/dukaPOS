import { jsPDF } from 'jspdf';

/**
 * User Guide & System Report PDF Generator
 * Uses standard Helvetica font hierarchy:
 * - Helvetica Bold for headers and key figures
 * - Helvetica Normal for body paragraphs, labels, and tables
 * - Helvetica Italic / Oblique for metadata, caveats, and timestamps
 */
export function generateUserGuidePDF({
  title = 'DukaPOS User Guide & Manual',
  subtitle = 'Comprehensive Operations & POS Terminal Guide',
  sections = [],
  companyName = 'DukaPOS System',
  author = 'System Administration',
  filename = 'dukapos_user_guide.pdf'
} = {}) {
  const doc = new jsPDF({
    unit: 'mm',
    format: 'a4',
    orientation: 'portrait'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentWidth = pageWidth - (margin * 2);
  let y = margin;

  const checkPageBreak = (neededSpace = 15) => {
    if (y + neededSpace > pageHeight - margin) {
      doc.addPage();
      y = margin;
      renderHeader();
    }
  };

  const renderHeader = () => {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(companyName, margin, 12);
    doc.text(new Date().toLocaleDateString('en-GB', { dateStyle: 'medium' }), pageWidth - margin, 12, { align: 'right' });
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.3);
    doc.line(margin, 14, pageWidth - margin, 14);
  };

  // Header on Page 1
  renderHeader();
  y = 28;

  // Title (Helvetica Bold)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(37, 99, 235); // #2563eb Transit Blue
  doc.text(title, margin, y);
  y += 10;

  // Subtitle (Helvetica Normal)
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(71, 85, 105);
  doc.text(subtitle, margin, y);
  y += 6;

  // Meta (Helvetica Italic)
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated by: ${author} | Version: 2.0.0`, margin, y);
  y += 10;

  // Horizontal divider
  doc.setDrawColor(37, 99, 235);
  doc.setLineWidth(0.8);
  doc.line(margin, y, pageWidth - margin, y);
  y += 10;

  // Default sections if none provided
  const guideSections = sections.length > 0 ? sections : [
    {
      heading: '1. POS Terminal & Fare Collection',
      content: 'Cashiers and transit operators can issue tickets, scan barcodes, and register digital and cash payments. Every transaction generates a cryptographic eTIMS-compliant invoice identifier.',
      note: 'Note: Ensure terminal is online or in offline sync mode before beginning shifts.'
    },
    {
      heading: '2. Transit Shifts & Auditing',
      content: 'Open and close daily shifts seamlessly. Reconciliation reports provide cash variance breakdowns, card settlements, and cashier accountability summaries.',
      note: 'Mandatory daily reconciliation is enforced at midnight EAT.'
    },
    {
      heading: '3. Telemetry & Fleet Tracking',
      content: 'Monitor live transit vehicle locations on the dark telemetry radar map. GPS pings update every 15 seconds with route deviation and speed alerts.',
      note: 'Telemetry radar tiles invert automatically under low ambient light conditions.'
    },
    {
      heading: '4. Inventory & Fuel Management',
      content: 'Track spare parts, fuel consumption per kilometer, and warehouse requisitions with low-stock alerts and automatic re-ordering points.'
    }
  ];

  // Render Sections
  guideSections.forEach((section, index) => {
    checkPageBreak(25);

    // Section Heading (Helvetica Bold)
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(15, 23, 42); // slate-900
    doc.text(section.heading || `Section ${index + 1}`, margin, y);
    y += 7;

    // Body text (Helvetica Normal)
    if (section.content) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(51, 65, 85); // slate-700
      const splitText = doc.splitTextToSize(section.content, contentWidth);
      splitText.forEach((line) => {
        checkPageBreak(7);
        doc.text(line, margin, y);
        y += 5.5;
      });
    }

    // Optional Note/Tip (Helvetica Italic)
    if (section.note) {
      checkPageBreak(12);
      y += 2;
      doc.setFillColor(248, 250, 252);
      doc.setDrawColor(203, 213, 225);
      doc.roundedRect(margin, y - 4, contentWidth, 10, 1.5, 1.5, 'FD');

      doc.setFont('helvetica', 'italic');
      doc.setFontSize(8.5);
      doc.setTextColor(71, 85, 105);
      doc.text(section.note, margin + 4, y + 2);
      y += 10;
    }

    y += 6;
  });

  // Footer on all pages (Page numbers)
  const totalPages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth / 2, pageHeight - 10, { align: 'center' });
  }

  if (filename) {
    doc.save(filename);
  }

  return doc;
}

export default generateUserGuidePDF;
